<#
.SYNOPSIS
    Demonstrates common parameters available in PowerShell cmdlets.

.DESCRIPTION
    PowerShell common parameters are built-in parameters automatically available 
    to all standard cmdlets and advanced functions (functions decorated with [CmdletBinding()]).
    They are implemented by the PowerShell engine, not by individual cmdlet developers.

.COMMON PARAMETERS
    - Verbose               Provides detailed operational information about what the cmdlet is doing.
    - Debug                 Displays programmer-level debugging messages.
    - ErrorAction           Determines how the cmdlet responds to a non-terminating error.
                            Values: Continue, SilentlyContinue, Stop, Inquire, Ignore.
    - ErrorVariable         Stores error messages generated by the command in a specified variable.
    - WarningAction         Determines how the cmdlet responds to a warning message.
                            Values: Continue, SilentlyContinue, Stop, Inquire, Ignore.
    - WarningVariable       Stores warning messages in a specified variable.
    - InformationAction     Determines how information stream messages are handled.
    - InformationVariable   Stores information stream messages in a specified variable.
    - OutVariable           Stores output objects in a specified variable in addition to sending them down the pipeline.
    - OutBuffer             Specifies the number of objects to buffer before calling the next pipeline element.
    - PipelineVariable      Stores the current pipeline object in a variable for use by downstream pipeline elements.
    - WhatIf                (Risk Mitigation) Explains what would happen if the command were executed without actually executing it.
    - Confirm               (Risk Mitigation) Prompts for confirmation before executing the action.

.EXAMPLE
#>

# Example 1: Using the -Verbose common parameter
# Displays step-by-step details of the operation target and status in the console.
new-item -ItemType File test.txt -Force -Verbose
remove-item test.txt -Verbose 

$Error.Clear()
# Example 2: Error Handling with -ErrorAction and -ErrorVariable
# -ErrorAction Silently Continue
remove-item test.txt
remove-item test.txt -ErrorAction SilentlyContinue
$Error[0]
#Use a variable to hold the error
remove-item test.txt -ErrorVariable myError
$myError


# -ErrorAction Stop converts non-terminating errors into terminating errors (catchable by try/catch).
# -ErrorVariable captures the error object into the specified variable (note: omit the '$' when passing the variable name).
try {
    Get-Item -Path "\NonExistentFile.txt" -ErrorVariable myError  -ErrorAction Stop #generate an error
    write-host "Hello"
}
catch {
    Write-Host "Caught an error using -ErrorAction Stop!" -ForegroundColor Red
    Write-Host "Error captured in `$myError : $($myError.Message)"
}

# Alternatively, suppress the error output in console while still recording it:
#Error stream is still utilized
$Error.Clear()
Get-Item -Path "~\NonExistentFile.txt" -ErrorAction SilentlyContinue -ErrorVariable capturedError
if ($capturedError) {
    Write-Host "File was not found, but error message was safely captured `$capturedError: `n $capturedError." -ForegroundColor Yellow
}
$Error #$Error still captures the error

# Example 3: Warning Handling with -WarningAction and -WarningVariable
# -WarningAction SilentlyContinue suppresses warning text on screen.
# -WarningVariable stores any emitted warning messages into the variable (omit '$' in parameter value).
Write-Warning "This is a test warning message."
Write-Warning "This is a test warning message." -WarningAction SilentlyContinue -WarningVariable myWarning
if ($myWarning) {
    Write-Host "Warning was suppressed from screen but stored in `$myWarning: $myWarning" -ForegroundColor Cyan
}

# Force a warning to prompt the user interactively:
#Warning data stream
Write-Warning "Disk space is low!" -WarningAction Inquire

# Example 4: Using Risk Mitigation Common Parameters (-WhatIf and -Confirm)
# Pre-checks what changes would occur without modifying system state
# Prompts the user interactively before making any actual changes
Get-process Safari
Stop-Process -Name Safari -WhatIf
Stop-Process -Name "Safari" -Confirm


